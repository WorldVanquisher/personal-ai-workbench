// PAI Worktrees page (experimental). Plain DOM, no external code. The server does every check;
// this page only shows what it says. Writes carry the session's CSRF token; a save names the
// exact revision confirmed; a publish names the exact preview reviewed.
"use strict";
const $ = (id) => document.getElementById(id);
let csrf = "", wts = [], cur = null, dirty = false, timer = null, lastWt = "", lastFile = "AGENTS.md";
let pending = null, prDigest = null, opener = null;

async function api(method, url, body) {
  const opt = { method, headers: { "X-PAI-CSRF": csrf }, credentials: "same-origin" };
  if (body) { opt.headers["Content-Type"] = "application/json"; opt.body = JSON.stringify(body); }
  const r = await fetch(url, opt);
  const data = await r.json().catch(() => ({}));
  return { status: r.status, data };
}
function say(msg) { $("state").textContent = msg; }
function showError(msg) { const e = $("error"); e.textContent = msg || ""; e.hidden = !msg; }
function el(tag, text, cls) { const e = document.createElement(tag); if (text !== undefined) e.textContent = text; if (cls) e.className = cls; return e; }
function facts(dl, rows) {
  dl.textContent = "";
  for (const [k, v, cls] of rows) { dl.append(el("dt", k)); dl.append(el("dd", v == null ? "—" : String(v), cls)); }
}
function setDirty(v) {
  dirty = v;
  say(!cur ? "" : (v ? "Unsaved changes" : "Saved"));
  $("state").className = "state" + (v ? " dirty" : "");
  $("save").disabled = !cur || !cur.writable || !v;
}

// ---- sections (the same rules as agentsmd.sections) ----
function sections(text) {
  const out = []; let inside = false, inh = false;
  const lines = text.split("\n");
  lines.forEach((line, i) => {
    const n = i + 1;
    if (/<!-- pai:managed:begin [^>]*-->/.test(line)) { inside = true; inh = false; }
    if (inside && line.startsWith("### ")) inh = line.startsWith("### Repository rules");
    let k = inside ? (inh ? "inherited" : "generated") : "manual";
    if (inside && line.includes("<!-- pai:managed:end -->")) { inside = false; inh = false; k = "generated"; }
    const last = out[out.length - 1];
    if (last && last.kind === k) last.end = n; else out.push({ kind: k, start: n, end: n });
  });
  const last = out[out.length - 1];
  if (last && last.kind === "manual" && lines[lines.length - 1] === "" && last.start === last.end) out.pop();
  return out;
}
const KIND = { manual: "manual (yours, kept byte for byte)", generated: "generated by pai", inherited: "inherited repository rules" };
function showSections() {
  const ul = $("sections"); ul.textContent = "";
  if (!cur) return;
  for (const s of sections($("text").value)) {
    const li = el("li", undefined, s.kind); const b = el("button", (s.start === s.end ? "Line " + s.start : "Lines " + s.start + "–" + s.end) + ": " + KIND[s.kind]);
    b.type = "button"; b.className = "ghost";
    b.addEventListener("click", () => selectLines(s.start, s.end));
    li.append(b); ul.append(li);
  }
}
// where the cursor is: the owner's own text, or pai's managed section (replaced when it is generated again)
function showWhere() {
  const t = $("text"), w = $("where");
  if (!cur || t.disabled) { w.textContent = ""; return; }
  const line = t.value.slice(0, t.selectionStart).split("\n").length;
  const s = sections(t.value).find((x) => line >= x.start && line <= x.end);
  w.textContent = !s ? "" : s.kind === "manual" ? "Line " + line + ": your text. pai keeps it byte for byte." :
    "Line " + line + ": " + KIND[s.kind] + ", inside pai's managed section. Edits here are replaced when the section is generated again; write your own notes outside it.";
}
function selectLines(a, b) {
  const t = $("text"); const lines = t.value.split("\n");
  let start = 0; for (let i = 0; i < a - 1; i++) start += lines[i].length + 1;
  let end = start; for (let i = a - 1; i < b; i++) end += lines[i].length + 1;
  t.focus(); t.setSelectionRange(start, Math.min(end, t.value.length));
}

// ---- preview ----
async function preview() {
  const r = await api("POST", "/api/preview", { text: $("text").value });
  if (r.status === 200) $("preview").innerHTML = r.data.html; // server-rendered, every source character escaped
}
function changed() { setDirty(true); showSections(); clearTimeout(timer); timer = setTimeout(preview, 250); }

// ---- worktrees ----
async function loadWorktrees() {
  const r = await api("GET", "/api/wt/list");
  if (r.status !== 200) return showError(r.data.error || "could not list the worktrees");
  wts = r.data.worktrees;
  const sel = $("wt"); sel.textContent = "";
  for (const w of wts) { const o = el("option", w.label); o.value = w.path; sel.append(o); }
  const first = wts.find((w) => !w.main) || wts[0];
  if (first) { sel.value = first.path; lastWt = first.path; await openFile(); }
}
function info() { return wts.find((w) => w.path === $("wt").value); }
function showInfo() {
  const w = info(); if (!w) return;
  facts($("wt-info"), [["path", w.path], ["branch", w.branch || "detached"], ["HEAD", (w.head || "").slice(0, 12)],
    ["changes", w.uncommitted ? w.uncommitted + " uncommitted path(s)" : "clean"],
    ["base", w.contains_last_fetched_base ? "contains the last fetched base" : "does NOT contain the last fetched base",
      w.contains_last_fetched_base ? "good" : "bad"]]);
}
// Each load answers only for the latest request: a slower earlier answer (a reload, then a quick switch to another
// worktree) must never put another worktree's file into the editor, where a save would write it.
let openSeq = 0, refSeq = 0;
async function openFile() {
  const seq = ++openSeq;
  showError(""); $("stale").hidden = true;
  const w = info(); showInfo();
  const r = await api("GET", "/api/wt/file?wt=" + encodeURIComponent($("wt").value) + "&file=" + encodeURIComponent($("file").value));
  if (seq !== openSeq) return;
  if (r.status !== 200) { cur = null; $("text").disabled = true; return showError(r.data.error || "could not open the file"); }
  cur = r.data; cur.writable = !w.main;
  $("path").textContent = (cur.exists ? "" : "NEW: ") + cur.file + " — " + cur.worktree + (cur.writable ? "" : " (main checkout: read only)");
  $("text").value = cur.text; $("text").disabled = !cur.writable;
  $("undo").disabled = !cur.undo; $("gen").hidden = !cur.writable;
  lastWt = $("wt").value; lastFile = $("file").value;
  setDirty(false); showSections(); preview();
  if (!$("view-ref").hidden) loadRefresh();
}
// a switch with unsaved text asks first; Cancel keeps the text and the selection
function guardSwitch(sel, back) {
  sel.addEventListener("change", () => {
    if (!dirty) return openFile();
    ask({ title: "DISCARD UNSAVED CHANGES?", text: "The editor has unsaved changes to " + cur.file + ". Switching discards them.",
      confirm: "Discard and switch", cancel: "Stay here" },
      () => openFile(), () => { sel.value = back(); say("Unsaved changes kept"); });
  });
}

// ---- dialog ----
function ask(o, yes, no) {
  pending = { yes, no }; opener = document.activeElement;
  $("dialog-title").textContent = o.title; $("dialog-text").textContent = o.text || "";
  const pre = $("diff"); pre.textContent = ""; pre.hidden = !o.diff;
  if (o.diff) renderDiff(pre, o.diff);
  $("pr-state").hidden = !o.pr;
  for (const r of document.querySelectorAll("input[name=prstate]")) r.checked = false;
  $("pr-reviewed").checked = false;
  $("confirm").textContent = o.confirm || "Confirm"; $("cancel").textContent = o.cancel || "Cancel";
  $("confirm").disabled = !!o.pr;
  $("dialog").hidden = false; $("cancel").focus();
}
function closeDialog(ok) {
  const p = pending; pending = null; $("dialog").hidden = true;
  if (opener && opener.focus) opener.focus();
  if (p) (ok ? p.yes : p.no || (() => {}))();
}
function renderDiff(pre, lines) {
  for (const line of lines.slice(2)) {
    const s = el("span", line + "\n");
    if (line.startsWith("+")) s.className = "add"; else if (line.startsWith("-")) s.className = "del"; else if (line.startsWith("@@")) s.className = "hunk";
    pre.append(s);
  }
  if (!lines.length) pre.textContent = "(no changes)";
}

// ---- generate (proposal only: nothing reaches the disk) ----
async function propose() {
  showError("");
  const checks = $("g-checks").value.split("\n").map((l) => l.trim()).filter(Boolean).map((l) => { const i = l.indexOf("="); return [l.slice(0, i).trim(), l.slice(i + 1).trim()]; });
  const accept = [...document.querySelectorAll("#g-list input:checked")].map((c) => c.value);
  say("Proposing…");
  const r = await api("POST", "/api/wt/generate", { wt: $("wt").value, file: $("file").value, text: $("text").value,
    goal: $("g-goal").value, scope: $("g-scope").value.split(",").map((s) => s.trim()).filter(Boolean),
    owner: $("g-owner").value, lane: $("g-lane").value, checks, accept, jev: $("g-jev").checked });
  if (r.status !== 200) { say(""); return showError(r.data.error || "could not propose"); }
  const d = r.data, list = $("g-list"); list.textContent = "";
  for (const p of d.proposals) {
    const li = el("li"); const lab = el("label", undefined, "inline"); const c = el("input"); c.type = "checkbox"; c.value = p.id;
    c.checked = d.accepted.includes(p.id);
    lab.append(c, document.createTextNode(p.text + " [" + p.id + ", " + p.source + (p.source === "jev" ? " " + p.score.toFixed(2) : "") + "]"));
    li.append(lab); list.append(li);
  }
  $("g-rules").hidden = !d.proposals.length;
  $("g-meta").textContent = "Template " + d.template + "; JEV " + d.jev.state + " (" + d.jev.detail + ")" +
    (d.conflicts.length ? ". Conflicts: " + d.conflicts.map((c) => c.source + " " + c.why).join("; ") : "") +
    (d.notes.length ? ". " + d.notes.join(" ") : "");
  say("Proposal ready (not applied)");
  ask({ title: "PUT THE PROPOSAL INTO THE EDITOR?", text: "Line by line, against the editor's current text. Nothing is written to disk; you still review and save.",
    diff: d.diff, confirm: "Put into the editor", cancel: "Discard the proposal" },
    () => { $("text").value = d.text; changed(); say("Proposal in the editor (unsaved)"); }, () => say("Proposal discarded"));
}

// ---- save, conflict, undo ----
async function sha256(text) {
  const b = await crypto.subtle.digest("SHA-256", new TextEncoder().encode(text));
  return [...new Uint8Array(b)].map((x) => x.toString(16).padStart(2, "0")).join("");
}
async function reviewSave() {
  const text = $("text").value;
  const r = await api("POST", "/api/wt/diff", { wt: cur.worktree, file: cur.file, text, base: cur.base });
  if (r.status !== 200) return showError(r.data.error || "could not diff");
  if (r.data.stale) { $("stale").hidden = false; $("stale").focus(); return say("Not saved: the file changed on disk"); }
  ask({ title: "SAVE " + cur.file, text: "Write " + cur.worktree + "/" + cur.file + "? Lines marked − are removed, + are added.",
    diff: r.data.diff, confirm: "Save this revision", cancel: "Keep editing" }, () => save(text));
}
async function save(text) {
  const r = await api("POST", "/api/wt/save", { wt: cur.worktree, file: cur.file, text, base: cur.base,
    confirm: await sha256(text), crlf: cur.crlf, bom: cur.bom });
  if (r.status === 409) { $("stale").hidden = false; $("stale").focus(); return say("Not saved: the file changed on disk"); }
  if (r.status !== 200) return showError(r.data.error || "could not save");
  cur.base = r.data.base; cur.exists = true; $("undo").disabled = false;
  if ($("text").value === text) setDirty(false);
  say(r.data.created ? "Created " + cur.file : "Saved");
}
async function undo() {
  ask({ title: "UNDO THE LAST SAVE?", text: "Puts back " + cur.file + " as it was before this page saved it (only if nobody changed it since).",
    confirm: "Undo the save", cancel: "Cancel" }, async () => {
    const r = await api("POST", "/api/wt/undo", { wt: cur.worktree, file: cur.file });
    if (r.status !== 200) return showError(r.data.error || "could not undo");
    await openFile(); say(r.data.removed ? "Undone: the file this page created was removed" : "Undone: the previous text is back");
  });
}

// ---- refresh ----
async function loadRefresh(recheck) {
  const seq = ++refSeq;
  const r = recheck ? await api("POST", "/api/wt/recheck", { wt: $("wt").value }) : await api("GET", "/api/wt/refresh?wt=" + encodeURIComponent($("wt").value));
  if (seq !== refSeq) return;
  if (r.status !== 200) return showError(r.data.error || "could not read the refresh state");
  const d = r.data, v = d.verify;
  const repo = d.plan.repository, rec = d.plan.recommendation;
  facts($("ref-facts"), [["repository", repo ? repo.path + " (" + repo.remote + " " + (repo.url || "no URL") + ")" : "—"],
    ["worktree", $("wt").value],
    ["expected base", d.expected ? d.plan.base.tracking_ref + " = " + d.expected : "never fetched"],
    ["actual HEAD", d.actual], ["contains base", v ? (v.contains_base ? "yes" : "no") : "—", v && v.contains_base ? "good" : "bad"],
    ["recommendation", rec ? rec.kind + ": " + rec.reasons.join("; ") : d.plan.error]]);
  const ready = $("ref-ready");
  ready.textContent = d.dispatch_ready ? "Ready for queue dispatch: this worktree contains the fetched base." :
    "Not ready for dispatch" + (v && v.problems.length ? ": " + v.problems.join("; ") : ": run the commands below, then Check again.");
  ready.className = "ready " + (d.dispatch_ready ? "good" : "bad");
  $("ref-bash").textContent = d.bash.join("\n"); $("ref-ps").textContent = d.powershell.join("\n");
  const ol = $("ref-attempts"); ol.textContent = "";
  for (const a of d.attempts) ol.append(el("li", a.at + "  expected " + (a.expected || "none").slice(0, 12) + "  actual " + (a.actual || "").slice(0, 12) + "  " + (a.ok ? "OK" : "not yet") + " — " + a.status));
  if (!d.attempts.length) ol.append(el("li", "none yet"));
  if (recheck) say(d.last.ok ? "Check: ready" : "Check: " + d.last.status);
}

// ---- split plan ----
async function planPreview() {
  showError("");
  const r = await api("POST", "/api/plan/propose", { parent: $("p-parent").value, goals: $("p-goals").value, workers: Number($("p-workers").value) });
  const out = $("p-out"); out.textContent = "";
  if (r.status !== 200) return showError(r.data.error || "could not split");
  const d = r.data, t = el("table", undefined, "split");
  const cols = ["Slice", "Item", "Worker", "Why this worker", "Paths", "Verify", "Prereqs", "Needs", "Queue"];
  const head = el("tr"); for (const h of cols) head.append(el("th", h));
  t.append(head);
  for (const s of d.plan.slices) {
    const tr = el("tr");
    [s.id + ": " + s.goal, s.item, s.worker, s.assigned_by, (s.paths || []).join(", "), s.verify || "—", s.prereqs || "—", (s.needs || []).join(", ") || "—", d.queues ? (d.queue_states[s.id] || "not queued") : "no --queues"].forEach((v, i) => {
      const td = el("td", v); td.dataset.label = cols[i]; tr.append(td);  // the label is shown when rows stack on a narrow screen
    });
    t.append(tr);
  }
  out.append(t);
  for (const p of d.problems) out.append(el("p", p.slice + " " + p.kind + ": " + p.detail, "problem"));
  out.append(el("p", d.problems.length ? "Fix the problems, then preview again." : "Clean. To queue it (from a terminal):", "hint"));
  if (!d.problems.length) out.append(el("pre", d.accept_command, "cmd"));
  say(d.problems.length ? d.problems.length + " problem(s) in the split" : "Split is clean");
}

// ---- PR ----
async function prPreview() {
  showError(""); prDigest = null; $("r-publish").disabled = true; $("r-result").textContent = "";
  say("Previewing (read only)…");
  const r = await api("POST", "/api/pr/preview", { wt: $("wt").value, title: $("r-title").value, body: $("r-body").value,
    base: $("r-base").value, github: $("r-github").value.trim() || null, offline: $("r-offline").checked, paths: $("r-paths").value.split("\n").map((s) => s.trim()).filter(Boolean) });
  if (r.status !== 200) { say(""); return showError(r.data.error || "could not preview"); }
  const p = r.data.preview;
  facts($("r-facts"), [["base", p.base.tracking_ref + " = " + (p.base.last_fetched || "never fetched")], ["head", (p.branch || "detached") + " = " + p.head],
    ["remote SHA", (p.pushed.sha || "not on the remote") + " (" + p.pushed.how + ")"], ["remote", p.remote.push_url],
    ["existing PR", p.existing_prs && p.existing_prs.length ? p.existing_prs.map((x) => x.url + " " + x.state).join(", ") : p.existing_prs_how]]);
  $("r-text").textContent = r.data.text; $("r-text").hidden = false;
  prDigest = r.data.digest; $("r-publish").disabled = !prDigest;
  say(prDigest ? "Preview clean: nothing was changed" : "Preview has problems: nothing was changed");
}
function prPublish() {
  ask({ title: "PUBLISH THIS PREVIEW?", text: "Commits only the approved paths with the reviewed message (hooks run), pushes without force, reads the remote SHA back, then opens or reuses the PR. Nothing is merged.",
    pr: true, confirm: "Publish", cancel: "Cancel" }, async () => {
    const st = document.querySelector("input[name=prstate]:checked");
    say("Publishing…");
    const r = await api("POST", "/api/pr/publish", { digest: prDigest, state: st && st.value, confirm: true });
    const res = $("r-result"); res.textContent = "";
    if (r.status !== 200) { say(""); return showError(r.data.error || "could not publish"); }
    res.append(el("pre", r.data.log, "cmd"));
    if (r.data.pr && /^https:\/\/github\.com\/[\w.-]+\/[\w.-]+\/pull\/\d+$/.test(r.data.pr)) {
      const a = el("a", "Open " + r.data.pr); a.href = r.data.pr; a.rel = "noreferrer noopener"; a.target = "_blank"; res.append(a);
    }
    say(r.data.code === 0 ? "Published" : "Stopped: see the log (rerun resumes)");
  });
}

// ---- tabs (arrow keys move between them) ----
function selectTab(btn) {
  for (const t of document.querySelectorAll("[role=tab]")) {
    const on = t === btn; t.setAttribute("aria-selected", on); t.tabIndex = on ? 0 : -1;
    $(t.getAttribute("aria-controls")).hidden = !on;
  }
  btn.focus();
  if (btn.id === "tab-ref") loadRefresh();
}

document.addEventListener("DOMContentLoaded", async () => {
  const s = await api("GET", "/api/session");
  if (s.status !== 200) return showError("Sign in with the link pai printed.");
  csrf = s.data.csrf;
  const tabs = [...document.querySelectorAll("[role=tab]")];
  tabs.forEach((t, i) => {
    t.addEventListener("click", () => selectTab(t));
    t.addEventListener("keydown", (e) => {
      if (e.key === "ArrowRight" || e.key === "ArrowLeft") { e.preventDefault(); selectTab(tabs[(i + (e.key === "ArrowRight" ? 1 : tabs.length - 1)) % tabs.length]); }
    });
  });
  guardSwitch($("wt"), () => lastWt); guardSwitch($("file"), () => lastFile);
  $("text").addEventListener("input", changed);
  for (const ev of ["keyup", "click", "select", "focus"]) $("text").addEventListener(ev, showWhere);
  $("save").addEventListener("click", reviewSave);
  $("undo").addEventListener("click", undo);
  $("g-run").addEventListener("click", propose);
  $("copy").addEventListener("click", () => navigator.clipboard && navigator.clipboard.writeText($("text").value).then(() => say("Draft copied")));
  $("reload").addEventListener("click", () => { dirty = false; openFile(); });
  $("ref-check").addEventListener("click", () => loadRefresh(true));
  $("p-run").addEventListener("click", planPreview);
  $("r-run").addEventListener("click", prPreview);
  $("r-publish").addEventListener("click", prPublish);
  for (const b of document.querySelectorAll(".copy-btn")) b.addEventListener("click", () => navigator.clipboard && navigator.clipboard.writeText($(b.dataset.copy).textContent).then(() => say("Copied")));
  $("confirm").addEventListener("click", () => closeDialog(true));
  $("cancel").addEventListener("click", () => closeDialog(false));
  $("dialog").addEventListener("keydown", (e) => {
    if (e.key !== "Tab") return;  // a modal dialog keeps keyboard focus inside it
    const f = [...$("dialog").querySelectorAll("button, input, pre[tabindex], [tabindex='0']")].filter((x) => !x.disabled && x.offsetParent !== null);
    if (!f.length) return;
    const first = f[0], last = f[f.length - 1];
    if (!e.shiftKey && document.activeElement === last) { e.preventDefault(); first.focus(); }
    else if (e.shiftKey && document.activeElement === first) { e.preventDefault(); last.focus(); }
  });
  document.addEventListener("keydown", (e) => { if (e.key === "Escape" && !$("dialog").hidden) closeDialog(false); });
  const prOk = () => { $("confirm").disabled = !(document.querySelector("input[name=prstate]:checked") && $("pr-reviewed").checked); };
  for (const r of document.querySelectorAll("input[name=prstate]")) r.addEventListener("change", prOk);
  $("pr-reviewed").addEventListener("change", prOk);
  const pv = (edit) => { $("panes").className = "panes " + (edit ? "show-edit" : "show-preview"); $("show-edit").setAttribute("aria-pressed", edit); $("show-preview").setAttribute("aria-pressed", !edit); };
  $("show-edit").addEventListener("click", () => pv(true)); $("show-preview").addEventListener("click", () => pv(false)); pv(true);
  window.addEventListener("beforeunload", (e) => { if (dirty) { e.preventDefault(); e.returnValue = ""; } });
  await loadWorktrees();
});
