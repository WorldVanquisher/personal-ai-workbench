"""Per-worktree agent instructions: an explicitly requested AGENTS.md section for one worktree.

    pai worktree init PATH --goal TEXT [--scope DIR ...] [--owner NAME] [--lane ID] [--check NAME=CMD ...]
                      [--file AGENTS.md] [--profile FILE] [--jev] [--accept RULE ...] [--write] [--json]
    pai worktree init PATH ... --export-profile FILE [--write]

Preview by default (the proposed file and a unified diff); --write writes the worktree's file.
Only one clearly delimited section is pai's: between `<!-- pai:managed:begin ... -->` and
`<!-- pai:managed:end -->`. Everything else in the file (what people wrote) is kept byte for
byte, with its BOM and line endings; a file without the section gets it appended. The same
inputs give the same bytes, so repeating it changes nothing. It never writes into the main
checkout, through a symbolic link, or outside the worktree.

The section holds this worktree's goal, directory scope, ownership and change boundary, the
required checks and how to report, the owner-only rules (push, PRs, deploy, credentials), and
the repository's own rules with their source (file:line), shown next to any proposed additions;
a template rule that contradicts an inherited one is reported as a conflict for the owner.
Task data (a task note's text) never goes into it, and copied rules lose credentials and local
machine paths.

Proposed additions come from a versioned rule library. With --jev, TypeSafe JEV (System One,
which answers typed questions and writes no text) scores how well each library rule applies to
this goal and scope; only the goal, the scope and the rule texts are sent. Without JEV, or when
it is not configured, times out or answers malformed, the deterministic template choice is used
and the state says which. Proposals are never applied by themselves: --accept RULE adds one.
"""
import difflib
import hashlib
import json
import os
import re
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
if HERE not in sys.path:
    sys.path.insert(0, HERE)
import gitprep  # noqa: E402

TEMPLATE_VERSION = "pai-agents/1"
BEGIN = "<!-- pai:managed:begin %s (generated by `pai worktree init`; edits inside are replaced) -->" % TEMPLATE_VERSION
BEGIN_RE = re.compile(r"<!-- pai:managed:begin [^>]*-->")
END = "<!-- pai:managed:end -->"
INSTRUCTION_NAMES = ("AGENTS.md", "CLAUDE.md", "CONTRIBUTING.md")
LOCAL_PATH_RE = re.compile(r"(?:/home/|/Users/|/root/|[A-Za-z]:\\\\Users\\\\|[A-Za-z]:\\Users\\|~/)[^\s`'\")\]]*")
PERMISSIVE_RE = re.compile(r"\b(push|deploy|merge|publish|force-push|commit and push|open a (?:pull request|pr))\b", re.I)
NEGATION_RE = re.compile(r"\b(never|do not|don't|must not|no|without|only the owner|owner)\b", re.I)

# The rule library: id -> (text, default applicability keywords). Versioned with TEMPLATE_VERSION.
LIBRARY = {
    "tests-first": ("Add or update a test that fails without your change, then make it pass.", ("test", "fix", "bug")),
    "small-commits": ("Keep each change small and focused on the goal; leave unrelated cleanups for later.", ()),
    "docs-with-code": ("Update the user-facing docs in the same change when behavior changes.", ("doc", "cli", "command")),
    "no-new-deps": ("Do not add a dependency without asking first.", ("dependency", "package", "library")),
    "migrations-reviewed": ("Treat schema or data migrations as owner decisions: propose, do not run them.",
                            ("migration", "database", "schema", "data")),
    "ui-a11y": ("Check keyboard focus, labels and narrow layouts for any UI change.", ("ui", "web", "page", "css", "browser")),
    "perf-measure": ("Measure before and after any performance change and report both numbers.", ("perf", "speed", "slow")),
}


class InitError(Exception):
    pass


def norm(text):
    return (text or "").replace("\r\n", "\n")


def sanitize(text):
    """(text without credentials and local machine paths, what was removed)."""
    removed = []
    try:
        sys.path.insert(0, os.path.dirname(HERE))
        from pai import privacy
        text, rem = privacy.scrub(text)
        removed += ["credential (%s)" % r["kind"] for r in rem]
    except ImportError:
        pass

    def path(m):
        removed.append("local path")
        return "<local path>"
    return LOCAL_PATH_RE.sub(path, text), removed


def inherited(wt, scope):
    """Repository rules that apply in this worktree: the root instruction files and nested ones
    inside the scope, as (source, line number, text) for every list item or rule-like line."""
    files = []
    for name in INSTRUCTION_NAMES:
        p = os.path.join(wt, name)
        if os.path.isfile(p) and not os.path.islink(p):
            files.append(name)
    for d in scope or []:
        base = os.path.join(wt, d)
        for root, dirs, fs in os.walk(base):
            dirs[:] = [x for x in dirs if not x.startswith(".")]
            for name in INSTRUCTION_NAMES:
                if name in fs:
                    rel = os.path.relpath(os.path.join(root, name), wt).replace(os.sep, "/")
                    if rel not in files:
                        files.append(rel)
    rules = []
    for rel in files:
        with open(os.path.join(wt, rel), encoding="utf-8-sig", errors="replace") as f:
            text = norm(f.read())
        inside = False
        for n, line in enumerate(text.split("\n"), 1):
            if BEGIN_RE.search(line):
                inside = True
            if inside:
                if END in line:
                    inside = False
                continue  # pai's own section is not a repository rule
            s = line.strip()
            if re.match(r"^([-*+]|\d+[.)])\s+\S", s):
                clean, _ = sanitize(re.sub(r"^([-*+]|\d+[.)])\s+", "", s))
                rules.append({"source": "%s:%d" % (rel, n), "text": clean, "nested": "/" in rel})
    return files, rules


def conflicts(rules):
    """Inherited rules that ask for something the template reserves for the owner."""
    out = []
    for r in rules:
        if PERMISSIVE_RE.search(r["text"]) and not NEGATION_RE.search(r["text"]):
            out.append({"source": r["source"], "text": r["text"],
                        "why": "it asks the agent to %s; the template keeps that with the owner"
                               % PERMISSIVE_RE.search(r["text"]).group(1).lower()})
    return out


def template_choice(goal, scope):
    """Deterministic fallback: library rules whose keywords appear in the goal or scope."""
    hay = (goal + " " + " ".join(scope or [])).lower()
    return {rid: (1.0 if any(k in hay for k in keys) else (0.5 if not keys else 0.0))
            for rid, (text, keys) in LIBRARY.items()}


def jev_scores(goal, scope):
    """({rule id: probability}, state, detail). Sends only the goal, the scope and the rule texts."""
    import jev
    if not jev.available():
        return None, "skipped", "no JEV key (TYPESAFE_API_KEY or the credential store)"
    state = "WORKTREE GOAL: %s\nDIRECTORY SCOPE: %s" % (goal, ", ".join(scope or []) or "(whole repository)")
    questions = {"rule-%s" % rid: {"type": "noul", "instructions": "This working rule helps an agent reach the goal "
                                   "above within the scope above: %s" % text} for rid, (text, _) in LIBRARY.items()}
    import socket
    import urllib.error
    try:
        ans = jev.ask(state, questions)
    except (socket.timeout, TimeoutError):
        return None, "timeout", "JEV did not answer in time"
    except urllib.error.URLError as e:
        slow = "timed out" in str(e.reason)
        return None, "timeout" if slow else "unavailable", jev._redact(str(e.reason), 200)
    except RuntimeError as e:
        return None, "error", jev._redact(str(e), 200)
    except ValueError:
        return None, "malformed", "the reply is not JSON"
    scores = {}
    for rid in LIBRARY:
        a = (ans or {}).get("rule-%s" % rid) if isinstance(ans, dict) else None
        v = a.get("noul") if isinstance(a, dict) else None
        if not isinstance(v, (int, float)) or isinstance(v, bool) or not 0 <= v <= 1:
            return None, "malformed", "the reply has no probability for rule %s" % rid
        scores[rid] = float(v)
    return scores, "ok", "scored by JEV"


def proposals(goal, scope, use_jev):
    """[{id, text, score, source, template}], provenance state, detail."""
    scores, state, detail = (None, "off", "JEV not requested") if not use_jev else jev_scores(goal, scope)
    source = "jev" if scores else "template"
    if scores is None:
        scores = template_choice(goal, scope)
    out = [{"id": rid, "text": LIBRARY[rid][0], "score": round(scores[rid], 3), "source": source,
            "template": TEMPLATE_VERSION} for rid in sorted(LIBRARY, key=lambda r: (-scores[r], r)) if scores[rid] >= 0.5]
    return out, state, detail


# The decisions a worker can be given (R4): each is assigned on its own; what is not given to the
# worker is the owner's. The owner-only list below is never delegated.
DECISIONS = {"implementation": "how to make the change inside your scope",
             "testing": "which tests to add or change, and how to run them",
             "design": "local design inside your scope: names, structure, helpers"}
OWNER_APPROVAL = ["pushing, opening or merging pull requests; packages, tags and releases",
                  "anything outside your scope, another lane's paths, or a shared or public interface",
                  "cloud or production writes, spending, credentials or secrets, real user data, database migrations, DNS"]


def decisions(reserved=()):
    """{"worker": [kind, ...], "owner": [kind, ...], "owner_approval": [text, ...]} for the section and previews."""
    bad = [r for r in reserved if r not in DECISIONS]
    if bad:
        raise InitError("--reserve takes %s, not %s" % (", ".join(DECISIONS), ", ".join(bad)))
    return {"worker": [k for k in DECISIONS if k not in reserved], "owner": [k for k in DECISIONS if k in reserved],
            "owner_approval": list(OWNER_APPROVAL)}


def other_lanes(wt):
    """[{lane, branch, scope}] of the other worktrees whose managed AGENTS.md declares a scope."""
    try:
        import splitplan
        owned, _main = splitplan.ownership(wt)
    except Exception:  # noqa: BLE001  a preview never fails because a neighbour's file is odd
        return []
    out = {}
    for scope, o in owned.items():
        if os.path.realpath(o["worktree"]) == wt:
            continue
        key = (o["lane"] or "?", o["branch"] or "?")
        out.setdefault(key, []).append(scope)
    return [{"lane": k[0], "branch": k[1], "scope": sorted(v)} for k, v in sorted(out.items())]


def section(info, accepted, nl="\n"):
    """The managed section's text (deterministic for the same inputs)."""
    s = [BEGIN, "## This worktree (pai)", ""]
    s.append("- Goal: %s" % info["goal"])
    s.append("- Branch: `%s`; base `%s` at `%s`" % (info["branch"] or "(detached)", info["base_ref"], (info["base_sha"] or "?")[:12]))
    if info["scope"]:
        s.append("- Change only files under: %s. Anything outside that scope: stop and ask the owner." %
                 ", ".join("`%s/`" % d.rstrip("/") for d in info["scope"]))
    else:
        s.append("- Scope: the whole repository; keep changes to what the goal needs.")
    s.append("- Owner: %s%s. Other worktrees own their own scopes; do not edit them." % (
        info["owner"] or "the repository owner", "; this is lane `%s`" % info["lane"] if info["lane"] else ""))
    s += ["", "### Checks and reporting", ""]
    for name, cmd in info["checks"]:
        s.append("- Run `%s` (%s) before you report." % (cmd, name))
    if not info["checks"]:
        s.append("- No checks are configured: say which you ran and their results.")
    s.append("- Report what changed (paths), each check with its exit code, and what is not verified.")
    if info.get("other_lanes"):
        s += ["", "### Lanes and write scopes", ""]
        mine = ", ".join("`%s/`" % d.rstrip("/") for d in info["scope"]) or "the whole repository"
        s.append("- %s (this worktree): writes %s" % ("lane `%s`" % info["lane"] if info["lane"] else "this lane", mine))
        for o in info["other_lanes"]:
            s.append("- lane `%s` (branch `%s`): %s; read-only for you" % (
                o["lane"], o["branch"], ", ".join("`%s/`" % d for d in o["scope"])))
    dec = info.get("decisions") or decisions()
    s += ["", "### Decisions you own", ""]
    for k in dec["worker"]:
        s.append("- %s: %s. Record what you chose, why, and how to reverse it." % (k.capitalize(), DECISIONS[k]))
    if not dec["worker"]:
        s.append("- None: the owner decides implementation, testing and design for this lane.")
    for k in dec["owner"]:
        s.append("- %s is reserved for the owner: propose, then wait." % k.capitalize())
    s += ["", "### Owner only", "",
          "- Do not push, open or merge pull requests, publish packages, tags or releases, deploy, or change credentials, "
          "secrets or remote settings.",
          "- Do not reset, stash, force or delete branches or worktrees. The owner publishes (`pai worktree publish`).",
          "- Ask the owner before: %s." % "; ".join(dec["owner_approval"][1:])]
    s += ["", "### When a decision is above your authority", "",
          "- Stop that part and do not act on it. Write the options, their trade-offs and your recommendation into your "
          "report or handoff; keep going with independent work; wait for the owner's answer."]
    s += ["", "### Repository rules (inherited; the source files decide)", ""]
    clash = {c["source"] for c in conflicts(info["inherited"])}
    for r in info["inherited"]:
        s.append("- %s (%s%s)" % (r["text"], r["source"], "; CONFLICTS with Owner only above: ask the owner before "
                                   "following it" if r["source"] in clash else ""))
    if not info["inherited"]:
        s.append("- (no instruction files found in this worktree)")
    if accepted:
        s += ["", "### Accepted additions (%s)" % TEMPLATE_VERSION, ""]
        for p in accepted:
            s.append("- %s (rule `%s`, %s)" % (p["text"], p["id"], p["source"]))
    s.append(END)
    return nl.join(s)


MARKER_RE = re.compile(r"pai:managed:", re.I)


def read_text(path, name):
    """A file's text for merging (BOM kept as U+FEFF, line endings as they are), or InitError:
    pai only rewrites UTF-8 files with LF or CRLF line endings, and says why it will not."""
    with open(path, "rb") as f:
        data = f.read()
    if data.startswith((b"\xff\xfe", b"\xfe\xff")):
        raise InitError("%s is UTF-16: pai writes only UTF-8, and nothing was written. Save it as UTF-8 (with or without "
                        "a BOM) and run again, or use --file with another name" % name)
    try:
        text = data.decode("utf-8")
    except UnicodeDecodeError as e:
        raise InitError("%s is not UTF-8 (byte offset %d): pai does not rewrite it, and nothing was written. Save it as UTF-8 "
                        "and run again, or use --file with another name" % (name, e.start))
    if "\r" in text.replace("\r\n", ""):
        raise InitError("%s has old Mac (CR-only) line endings: pai keeps LF and CRLF files as they are but does not "
                        "rewrite this one, and nothing was written. Convert it to LF or CRLF and run again" % name)
    return text


def marker_problems(body):
    """What is wrong with the managed-section markers, with line numbers and the fix ([] when
    there are none, or exactly one begin followed by one end)."""
    begins, ends, bad = [], [], []
    for n, line in enumerate(body.replace("\r\n", "\n").split("\n"), 1):
        if BEGIN_RE.search(line):
            begins.append(n)
        elif END in line:
            ends.append(n)
        elif MARKER_RE.search(line):
            bad.append(n)
    out = []
    if bad:
        out.append("line(s) %s look like a pai marker but are not one (a marker is a whole `<!-- pai:managed:begin ... -->` "
                   "or `%s`): correct or delete them" % (", ".join(map(str, bad)), END))
    if len(begins) > 1:
        out.append("%d managed sections begin (lines %s): keep one, delete the others from their begin line to their end "
                   "line" % (len(begins), ", ".join(map(str, begins))))
    if begins and not [e for e in ends if e > begins[0]]:
        out.append("the managed section that begins on line %d has no end marker: add the line `%s` after its last line, "
                   "or delete the section from line %d" % (begins[0], END, begins[0]))
    stray = [e for e in ends if not begins or e < begins[0]] + [e for e in ends if begins and e > begins[0]][1:]
    if stray:
        out.append("line(s) %s hold an end marker that closes no section: delete them" % ", ".join(map(str, stray)))
    return out


def merge(existing, managed):
    """(new text, how): the existing file with only the managed section replaced (or appended).
    `existing` is the raw text (BOM and line endings as they are)."""
    bom = existing.startswith("﻿")
    body = existing[1:] if bom else existing
    nl = "\r\n" if "\r\n" in body else "\n"
    managed = managed.replace("\n", nl)
    problems = marker_problems(body)
    if problems:
        raise InitError("the file's pai markers need fixing by hand first (pai never edits outside its own section; "
                        "nothing was written): " + "; ".join(problems))
    m = BEGIN_RE.search(body)
    if m:
        end = body.find(END, m.start())
        new = body[:m.start()] + managed + body[end + len(END):]
        how = "replaced the managed section"
    elif body:
        sep = "" if body.endswith(nl * 2) else (nl if body.endswith(nl) else nl * 2)
        new = body + sep + managed + nl
        how = "appended the managed section; the rest is unchanged"
    else:
        new = managed + nl
        how = "created"
    return ("﻿" if bom else "") + new, how


def sections(text):
    """[{kind: manual|generated|inherited, start, end}] (1-based, inclusive line ranges) for the
    editor: pai's managed section is `generated`, its inherited-rules part `inherited`, the rest
    (what people wrote) `manual`."""
    out, kind = [], None
    lines = norm(text).lstrip("\ufeff").split("\n")
    inside = inherited_part = False
    for n, line in enumerate(lines, 1):
        if BEGIN_RE.search(line):
            inside, inherited_part = True, False
        if inside and line.startswith("### "):
            inherited_part = line.startswith("### Repository rules")
        k = ("inherited" if inherited_part else "generated") if inside else "manual"
        if inside and END in line:
            inside = inherited_part = False
            k = "generated"
        if out and out[-1]["kind"] == k:
            out[-1]["end"] = n
        else:
            out.append({"kind": k, "start": n, "end": n})
    if out and out[-1]["kind"] == "manual" and lines[-1] == "" and out[-1]["start"] == out[-1]["end"]:
        out.pop()  # the empty piece after a final newline
    return out


REF_NAME = re.compile(r"^(?!-)(?!.*\.\.)[A-Za-z0-9._/-]{1,100}(?<![./])$")


def plan(path, goal, scope=(), owner=None, lane=None, checks=(), file="AGENTS.md", use_jev=False, accept=(), profile=None,
         existing=None, reserve=(), remote="origin", base="main"):
    """The proposal for one worktree. `existing` (the editor's unsaved text) replaces the file's
    content as the text the section is merged into; the diff is then against that text.
    `remote`/`base` name the base the section records (`<remote>/<base>`), the same pair
    `pai worktree refresh` and `pai worktree web` take; nothing is fetched here."""
    for what, v in (("--remote", remote), ("--base", base)):
        if not REF_NAME.match(str(v or "")):
            raise InitError("%s %r is not a plain remote or branch name" % (what, v))
    wt = os.path.realpath(os.path.abspath(os.path.expanduser(path)))
    if gitprep.toplevel(wt) != wt:
        raise InitError("%s is not the top of a Git worktree" % wt)
    cdir = gitprep.common_dir(wt)
    if os.path.basename(cdir) == ".git" and os.path.dirname(cdir) == wt:
        raise InitError("%s is the main checkout; pai writes per-worktree instructions only into a linked worktree "
                        "(see `pai worktree refresh` for a fresh one)" % wt)
    if os.sep in file or "/" in file or file in ("", ".", ".."):
        raise InitError("--file must be a file name at the worktree root, such as AGENTS.md")
    target = os.path.join(wt, file)
    if os.path.islink(target):
        raise InitError("%s is a symbolic link; pai does not write through it" % file)
    new_dirs = []
    for d in scope:
        full = os.path.realpath(os.path.join(wt, d))
        if os.path.isabs(d) or not full.startswith(wt + os.sep) or (os.path.exists(full) and not os.path.isdir(full)) \
                or os.path.relpath(full, wt).replace(os.sep, "/").split("/")[0] == ".git":
            raise InitError("scope %r is not a folder inside the worktree" % d)
        if not os.path.exists(full):
            new_dirs.append(d)
    if profile:
        with open(profile, encoding="utf-8") as f:
            prof = json.load(f)
        if prof.get("format") != "pai-rule-profile":
            raise InitError("%s is not a pai rule profile" % profile)
        checks = list(checks) + [tuple(c) for c in prof.get("checks", []) if tuple(c) not in [tuple(x) for x in checks]]
        accept = list(accept) + [a for a in prof.get("accepted", []) if a not in accept]
    base_ref = "%s/%s" % (remote, base)
    goal_clean, goal_removed = sanitize(goal)
    files, rules = inherited(wt, scope)
    props, jstate, jdetail = proposals(goal_clean, list(scope), use_jev)
    unknown = [a for a in accept if a not in LIBRARY]
    if unknown:
        raise InitError("unknown rule(s) %s (library %s: %s)" % (", ".join(unknown), TEMPLATE_VERSION, ", ".join(sorted(LIBRARY))))
    accepted = [dict(p) for p in props if p["id"] in accept] + [
        {"id": a, "text": LIBRARY[a][0], "score": None, "source": "owner", "template": TEMPLATE_VERSION}
        for a in accept if a not in [p["id"] for p in props]]
    info = {"worktree": wt, "file": file, "goal": goal_clean, "scope": [d.rstrip("/") for d in scope], "owner": owner,
            "lane": lane, "checks": [tuple(c) for c in checks], "branch": gitprep.current_branch(wt),
            "base_ref": base_ref, "base_sha": gitprep.rev(wt, "refs/remotes/" + base_ref), "inherited": rules,
            "instruction_files": files, "decisions": decisions(reserve), "other_lanes": other_lanes(wt)}
    raw = ""
    if os.path.exists(target):
        raw = read_text(target, file)
    disk = raw
    if existing is not None:
        raw = existing
    new, how = merge(raw, section(info, accepted))
    tracked = bool(gitprep.out(wt, "ls-files", "--error-unmatch", "--", file))
    diff = list(difflib.unified_diff(norm(raw).split("\n"), norm(new).split("\n"), "a/" + file, "b/" + file, lineterm=""))
    entry = {"claude_md": "CLAUDE.md" in files, "imports_agents": False}
    if entry["claude_md"]:
        with open(os.path.join(wt, "CLAUDE.md"), encoding="utf-8-sig", errors="replace") as f:
            entry["imports_agents"] = "@AGENTS.md" in f.read()
    notes = ["scope %s does not exist yet (the worker creates it)" % d for d in new_dirs]
    import splitplan
    for o in info["other_lanes"]:
        for d in info["scope"] or [""]:
            hit = [x for x in o["scope"] if splitplan.overlaps(d, x)]
            if hit:
                notes.append("CONTESTED: scope %s overlaps lane %s's %s (branch %s): give each path to one lane; `pai plan "
                             "check` refuses slices that write another lane's paths" % (
                                 "`%s/`" % d if d else "(the whole repository)", o["lane"], ", ".join("`%s/`" % x for x in hit),
                                 o["branch"]))
    if file == "AGENTS.md" and entry["claude_md"] and not entry["imports_agents"]:
        notes.append("Claude Code reads CLAUDE.md, Codex reads AGENTS.md: for a Claude lane, add the line `@AGENTS.md` to "
                     "CLAUDE.md yourself, or run with --file CLAUDE.md")
    if tracked:
        notes.append("%s is tracked by Git: the managed section will show as a change; leave it out of PR paths" % file)
    return {"worktree": wt, "file": file, "target": target, "how": how if new != raw else "unchanged",
            "unchanged": new == raw, "old_sha256": hashlib.sha256(disk.encode("utf-8")).hexdigest(),
            "sections": sections(new),
            "new": new, "diff": diff, "inherited": rules, "instruction_files": files, "conflicts": conflicts(rules),
            "proposals": props, "accepted": [a["id"] for a in accepted], "jev": {"state": jstate, "detail": jdetail},
            "template": TEMPLATE_VERSION, "removed_from_goal": goal_removed, "notes": notes, "entry_points": entry,
            "decisions": info["decisions"], "other_lanes": info["other_lanes"]}


# `--target claude-local` (PRM-D9 = A, R6-COR-057..059; default off): the lane's L2 section goes to
# CLAUDE.local.md, which Claude Code reads next to CLAUDE.md, git never sees (info/exclude), and
# each worktree has its own. AGENTS.md is not touched, so the worktree stays clean for continuations
# and reuse. Codex lanes keep AGENTS.md (Codex does not read CLAUDE.local.md).
TARGETS = {"agents": "AGENTS.md", "claude-local": "CLAUDE.local.md"}
LOCAL_FILE = "CLAUDE.local.md"


def exclude_local(wt, name=LOCAL_FILE):
    """Add `/NAME` to the repository's info/exclude (shared by its worktrees) unless git already ignores
    it; returns True when a line was added. NAME is then never staged by `git add -A` either."""
    if subprocess.run([gitprep.git_bin(), "-C", wt, "check-ignore", "-q", "--no-index", name],
                      capture_output=True, stdin=subprocess.DEVNULL).returncode == 0:
        return False  # already ignored (an earlier run, or the repository's own .gitignore)
    cdir = gitprep.common_dir(wt)
    path = os.path.join(cdir, "info", "exclude")
    os.makedirs(os.path.dirname(path), exist_ok=True)
    old = ""
    if os.path.exists(path):
        with open(path, encoding="utf-8", errors="replace") as f:
            old = f.read()
    with open(path, "a", encoding="utf-8") as f:
        f.write(("" if not old or old.endswith("\n") else "\n") +
                "# pai: per-worktree Claude instructions, never committed (R6-COR-059)\n/%s\n" % name)
        f.flush()
        os.fsync(f.fileno())
    return True


def write(p):
    """Write the planned file (atomic), refusing when it changed since the plan was made."""
    raw = ""
    if os.path.exists(p["target"]):
        if os.path.islink(p["target"]):
            raise InitError("%s became a symbolic link; nothing written" % p["file"])
        raw = read_text(p["target"], p["file"])
    if hashlib.sha256(raw.encode("utf-8")).hexdigest() != p["old_sha256"]:
        raise InitError("%s changed since the preview; nothing written" % p["file"])
    if p["unchanged"]:
        return False
    if p["file"] == LOCAL_FILE:  # excluded before it exists: there is no moment git could see it
        exclude_local(p["worktree"])
    tmp = p["target"] + ".pai-%d.tmp" % os.getpid()
    with open(tmp, "wb") as f:
        f.write(p["new"].encode("utf-8"))
    os.replace(tmp, p["target"])
    return True


def profile(p, checks):
    """A reusable, reviewable rule profile: accepted rule ids and checks; no goal, no paths."""
    text = json.dumps({"format": "pai-rule-profile", "template": TEMPLATE_VERSION, "accepted": p["accepted"],
                       "checks": [list(c) for c in checks]}, indent=1)
    clean, removed = sanitize(text)
    return clean, removed


def render(p):
    out = ["worktree    %s" % p["worktree"], "file        %s (%s)" % (p["file"], p["how"]),
           "template    %s; JEV %s (%s)" % (p["template"], p["jev"]["state"], p["jev"]["detail"]),
           "inherited   %d rule(s) from %s" % (len(p["inherited"]), ", ".join(p["instruction_files"]) or "no instruction file")]
    dec = p.get("decisions") or decisions()
    out.append("worker      decides %s; records each choice, why and how to reverse it" % (
        ", ".join(dec["worker"]) or "nothing on its own"))
    out.append("OWNER       approves %s%s" % ("; ".join(dec["owner_approval"]), "; and decides %s" % ", ".join(dec["owner"])
                                             if dec["owner"] else ""))
    for o in p.get("other_lanes") or []:
        out.append("lane        %s (branch %s) writes %s" % (o["lane"], o["branch"], ", ".join(o["scope"])))
    for c in p["conflicts"]:
        out.append("CONFLICT    %s %r: %s" % (c["source"], c["text"], c["why"]))
    out.append("proposed    (not applied; --accept RULE adds one)")
    for pr in p["proposals"]:
        out.append("  %-20s %-8s %s  [%s%s]" % (pr["id"], "accepted" if pr["id"] in p["accepted"] else "", pr["text"],
                                               pr["source"], ", %.2f" % pr["score"] if pr["source"] == "jev" else ""))
    for n in p["notes"]:
        out.append("note        %s" % n)
    if p["removed_from_goal"]:
        out.append("removed     %s from the goal text" % ", ".join(p["removed_from_goal"]))
    out.append("")
    out += p["diff"] or ["(no change)"]
    return "\n".join(out)
