#!/usr/bin/env python3
"""Inventory of the user-facing `pai` commands and entry points, and a check that every `pai ...`
example in the help texts and the shipped documents is an invocation the parsers accept.

    python3 -B tools/command_inventory.py                  the inventory (Markdown) on stdout
    python3 -B tools/command_inventory.py --json           the same as JSON
    python3 -B tools/command_inventory.py --check-examples [FILE ...]
        parse every `pai ...` example found in the help of every command and subcommand and in the
        given files (default: the shipped Markdown documents); nothing is executed. Exit 1 when an
        example does not parse. Synopsis lines ([optional], a|b, ..., <PLACEHOLDER>) are counted
        and listed as not checked.

Routing follows pai/launch.py exactly (workbench commands to swarm/workbench.py, the rest to
pai/cli.py), so an example is checked against the parser that would really receive it.
Standard library only; run from a checkout.
"""
import argparse
import contextlib
import io
import json
import os
import re
import shlex
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)
sys.path.insert(0, os.path.join(ROOT, "swarm"))

from pai import cli, launch  # noqa: E402
import workbench  # noqa: E402

DOCS = ["README.md", "README.zh-CN.md", "QUICKSTART.md", "QUICKSTART.zh-CN.md", "INSTALL.md", "REFERENCE.md",
        "swarm/WORKBENCH.md", "swarm/RUN-STATE.md", "swarm/BACKENDS.md", "swarm/CONTINUATION.md"]
ENTRY_POINTS = [
    ("pai (console script)", "pyproject.toml [project.scripts] pai = pai.launch:main", "uv tool install / pip; all systems"),
    ("bin/pai", "release archive and checkout: POSIX sh launcher -> bin/pai.py", "Linux, macOS, WSL"),
    ("bin/pai.cmd", "release archive: cmd/PowerShell launcher -> py -3 bin/pai.py", "native Windows (core commands only)"),
    ("bin/pai.py", "python3 bin/pai.py ARGS -> pai.launch.main", "every system with Python 3.11+"),
    ("python3 -m pai", "pai/__main__.py -> pai.cli.main (PAI's own commands, no workbench routing)", "every system"),
]


def subparsers(p):
    for act in p._actions:
        if isinstance(act, argparse._SubParsersAction):
            return act
    return None


def walk(p, path):
    """[(command path, parser)] for a parser and every sub-command below it."""
    out = [(path, p)]
    sp = subparsers(p)
    if sp:
        for name, child in sp.choices.items():
            out += walk(child, path + [name])
    return out


def options(p):
    res = []
    for act in p._actions:
        if isinstance(act, (argparse._HelpAction, argparse._SubParsersAction, argparse._VersionAction)):
            continue
        res.append(" / ".join(act.option_strings) if act.option_strings else act.dest.upper())
    return res


def helps(p):
    sp = subparsers(p)
    return {} if not sp else {a.dest: a.help for a in sp._choices_actions}


def inventory():
    core, wb = cli._parser(), workbench.parser()
    rows = []
    for parser, owner in ((core, "core"), (wb, "workbench")):
        top = helps(parser)
        for path, p in walk(parser, []):
            if not path:
                continue
            name = path[0]
            if owner == "core" and name in ("init", "doctor"):
                routed = "core when PAI-only options are given (%s), else the workbench" % (
                    "--vault/--memory/--inbox" if name == "init" else "PROJECT or --agents")
            elif owner == "workbench" and name in ("init", "doctor"):
                routed = "workbench (core when PAI-only options are given)"
            elif owner == "workbench":
                routed = "workbench" if name in launch.WORKBENCH else "NOT ROUTED"
            else:
                routed = "core"
            rows.append({"command": "pai " + " ".join(path), "owner": owner, "routed": routed,
                         "help": top.get(name) if len(path) == 1 else helps(walk_get(parser, path[:-1])).get(path[-1]),
                         "options": options(p), "windows": owner == "core" or name == "edit"})
    rows.append({"command": "pai edit FILE.md", "owner": "mdserver", "routed": "pai/launch.py before any other routing",
                 "help": "one Markdown file in the browser (loopback only)", "options": [], "windows": True})
    return {"schema": "pai_command_inventory_v1", "entry_points": [dict(zip(("entry", "how", "where"), e))
                                                                    for e in ENTRY_POINTS],
            "commands": rows}


def walk_get(p, path):
    for name in path:
        p = subparsers(p).choices[name]
    return p


def markdown(inv):
    out = ["# pai commands and entry points (generated by tools/command_inventory.py)", "",
           "| Entry point | How | Where |", "| --- | --- | --- |"]
    out += ["| `%s` | %s | %s |" % (e["entry"], e["how"], e["where"]) for e in inv["entry_points"]]
    out += ["", "| Command | Routed to | Native Windows | Help |", "| --- | --- | --- | --- |"]
    for r in inv["commands"]:
        out.append("| `%s` | %s | %s | %s |" % (r["command"], r["routed"], "yes" if r["windows"] else "no (WSL)",
                                               (r["help"] or "").replace("|", "\\|")))
    return "\n".join(out) + "\n"


# ---------------------------------------------------------------- example checks

SYNOPSIS = re.compile(r"\[|\]|\||\.\.\.|…|<[^>]*>|\bARGS\b|->|→")
PLACEHOLDERS = {"FILE": "cards.json", "FILE.md": "note.md", "NOTE.md": "note.md", "NOTE": "task-a", "LANE": "a",
                "NAME": "task-a", "TITLE": "Add a flag", "RUN": "run1", "RUN_ID": "run1", "PROJECT": "demo", "ID": "R2-001",
                "STATE": "done", "PATH": "x", "SHELL": "bash", "HANDOFF": "HANDOFF.md", "LIST": "items.md", "N": "1",
                "TEXT": "x"}


def _clean(raw):
    raw = re.sub(r"^(?:\$|>)\s+", "", raw.strip())
    raw = re.split(r"\s{2,}|\s+#\s", raw, maxsplit=1)[0].strip()  # a column of explanation, or a # comment
    return raw


def examples_in(text, markdown=False):
    """[(line number, example)]: in help texts, indented lines that start with `pai `; in Markdown,
    lines in fenced code blocks and inline code spans that start with `pai `. Prose is not an example."""
    found, lines = [], text.replace("\r\n", "\n").split("\n")
    fenced, i = False, 0
    while i < len(lines):
        line, start = lines[i], i + 1
        if markdown and line.strip().startswith("```"):
            fenced = not fenced
            i += 1
            continue
        block = fenced if markdown else bool(re.match(r"^\s+\S", line))
        stripped = re.sub(r"^(?:\$|>)\s+", "", line.strip())
        if block and re.match(r"^pai\s+[a-z]", stripped):
            raw = line.strip()
            while raw.endswith("\\") and i + 1 < len(lines):
                i += 1
                raw = raw[:-1].rstrip() + " " + lines[i].strip()
            found.append((start, _clean(raw), False))
        elif markdown and not fenced:
            for mt in re.finditer(r"`(pai\s+[a-z][^`]*)`", line):
                found.append((start, _clean(mt.group(1)), True))
        i += 1
    return found


def check(example, reference=False):
    """(state, detail): ok | ref | synopsis | FAIL. A reference (inline code in prose, or a bare
    command name) only has to name commands and options that exist; an example must parse."""
    body = example.split(" | ")[0].strip()  # an example piped into another program: check the pai part
    if SYNOPSIS.search(body):
        return "synopsis", "has [optional], a|b, ... or <PLACEHOLDER>"
    try:
        argv = shlex.split(body)[1:]
    except ValueError as e:
        return "FAIL", "cannot be split into arguments: %s" % e
    alt = next((i for i, x in enumerate(argv) if re.fullmatch(r"[a-z][a-z-]*(?:/[a-z][a-z-]*)+", x)), None)
    if alt is not None:  # `pai task new/list`: shorthand for several subcommands; each must parse
        res = [check(" ".join(["pai"] + argv[:alt] + [x] + argv[alt + 1:]), reference) for x in argv[alt].split("/")]
        bad = [r for r in res if r[0] == "FAIL"]
        return bad[0] if bad else (res[0][0], "each of %s" % argv[alt].replace("/", ", "))
    argv = [PLACEHOLDERS.get(a, a) for a in argv]
    argv = [re.sub(r"=([A-Z][A-Z_]+)$", lambda m: "=" + PLACEHOLDERS.get(m.group(1), "x"), a) for a in argv]
    if argv[:1] == ["edit"]:
        if len(argv) >= 2:
            return "ok", "pai edit (browser editor)"
        return ("ref", "pai edit named in the text") if reference else ("FAIL", "pai edit needs a file")
    cmd = launch.workbench_command(argv)
    parser = workbench.parser() if cmd else cli._parser()
    err = io.StringIO()
    with contextlib.redirect_stderr(err), contextlib.redirect_stdout(io.StringIO()):
        try:
            parser.parse_args(argv)
        except SystemExit as e:
            if e.code not in (0, None):
                msg = (err.getvalue().strip().splitlines() or ["exit %s" % e.code])[-1]
                bare = all(not x.startswith("-") for x in argv) and "are required" in msg
                if (reference or bare) and ("are required" in msg or "expected one argument" in msg):
                    return "ref", "names exist; arguments left out in the text"
                return "FAIL", msg
    return ("ref" if reference else "ok"), "workbench" if cmd else "core"


def help_texts():
    out = []
    for parser, owner in ((cli._parser(), "core"), (workbench.parser(), "workbench")):
        for path, p in walk(parser, []):
            out.append(("help: %s pai %s" % (owner, " ".join(path)), p.format_help(), False))
    out.append(("help: pai (quick start)", launch.QUICKSTART, False))
    return out


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--json", action="store_true")
    ap.add_argument("--check-examples", nargs="*", metavar="FILE")
    ap.add_argument("--out", help="write the result here as well")
    a = ap.parse_args(argv)
    if a.check_examples is None:
        inv = inventory()
        text = json.dumps(inv, indent=1, sort_keys=True) + "\n" if a.json else markdown(inv)
        sys.stdout.write(text)
        if a.out:
            with open(a.out, "w", encoding="utf-8") as f:
                f.write(text)
        return 0
    sources = help_texts()
    for f in a.check_examples or DOCS:
        path = f if os.path.isabs(f) else os.path.join(ROOT, f)
        with open(path, encoding="utf-8") as fh:
            sources.append((os.path.relpath(path, ROOT), fh.read(), True))
    results = []
    for where, text, md in sources:
        for line, ex, ref in examples_in(text, md):
            state, detail = check(ex, ref)
            results.append({"where": where, "line": line, "example": ex, "state": state, "detail": detail})
    seen, uniq = set(), []
    for r in results:
        key = (r["where"], r["example"])
        if key not in seen:
            seen.add(key)
            uniq.append(r)
    counts = {s: sum(1 for r in uniq if r["state"] == s) for s in ("ok", "ref", "synopsis", "FAIL")}
    lines = ["%-8s %s:%s  %s%s" % (r["state"], r["where"], r["line"], r["example"],
                                   "  -> %s" % r["detail"] if r["state"] == "FAIL" else "") for r in uniq]
    lines.append("examples: %d parsed ok, %d references with valid names, %d synopsis lines not checked, %d FAILED "
                 "(from %d help texts and %d file(s))" % (counts["ok"], counts["ref"], counts["synopsis"], counts["FAIL"],
                                                          len(help_texts()), len(a.check_examples or DOCS)))
    text = "\n".join(lines) + "\n"
    sys.stdout.write(text)
    if a.out:
        with open(a.out, "w", encoding="utf-8") as f:
            f.write(text)
    return 1 if counts["FAIL"] else 0


if __name__ == "__main__":
    sys.exit(main())
